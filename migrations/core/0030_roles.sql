-- ROLE-001. Terrace staff roles over Base's sign-in tier (owner, admin, member): the role each non-owner
-- operator holds, whether it covers every portfolio or only those the owner assigned, the one capability
-- table every page, API read, download, export and command checks in D1, and the append-only history of
-- the owner's role and assignment changes. Existing admins become portfolio managers over all portfolios;
-- existing members keep prepare-only access over all portfolios.
CREATE TABLE tt_staff_roles (
 operator_id TEXT PRIMARY KEY,
 role TEXT NOT NULL CHECK(role IN ('portfolio_manager','leasing','bookkeeper','accountant','maintenance_coordinator','member')),
 all_portfolios INTEGER NOT NULL CHECK(all_portfolios IN (0,1)),
 version INTEGER NOT NULL DEFAULT 1 CHECK(version>0),
 set_by TEXT NOT NULL, set_at TEXT NOT NULL
);
CREATE TABLE tt_role_portfolios (
 operator_id TEXT NOT NULL REFERENCES tt_staff_roles(operator_id) ON DELETE CASCADE,
 portfolio_id TEXT NOT NULL REFERENCES tt_portfolios(id),
 PRIMARY KEY(operator_id,portfolio_id)
);
CREATE TABLE tt_role_actions (role TEXT NOT NULL, action TEXT NOT NULL, PRIMARY KEY(role,action));
CREATE TABLE tt_role_changes (
 id TEXT PRIMARY KEY, operator_id TEXT NOT NULL, role TEXT NOT NULL, all_portfolios INTEGER NOT NULL, portfolios TEXT NOT NULL,
 changed_by TEXT NOT NULL, changed_at TEXT NOT NULL
);
CREATE TRIGGER tt_role_change_immutable BEFORE UPDATE ON tt_role_changes BEGIN SELECT RAISE(ABORT,'A role change is never edited'); END;
