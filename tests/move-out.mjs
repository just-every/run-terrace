async function unchanged(h){
 const result={}
 for(const table of ['tt_charges','tt_receipts','tt_journal','tt_payments','tt_maintenance_jobs','tt_turnovers','tt_units'])result[table]=(await h.db.prepare('SELECT * FROM '+table+' ORDER BY id').all()).results
 result.messages=h.messages.length
 return result
}
